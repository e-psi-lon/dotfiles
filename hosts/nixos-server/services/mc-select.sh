SERVICE="mc-server.service"
MC_USER="minecraft"
MC_GROUP="minecraft"

die() { echo "mc-select: $*" >&2; exit 1; }

usage() {
    cat >&2 <<EOF
Usage:
    mc-select list
    mc-select select [server]        (fzf picker when no server is given)
    mc-select create <server> <8|17|25>
EOF
    exit 1
}

need_root() {
    if [ "$(id -u)" -ne 0 ]; then die "run with sudo"; fi
}

valid_name() { [[ "$1" =~ ^[A-Za-z0-9][A-Za-z0-9._-]*$ ]]; }

list_names() {
    find "$SERVERS_ROOT" -mindepth 1 -maxdepth 1 -type d -printf '%f\n' | sort
}

cmd_list() {
    local active name
    active=$(readlink -f "$ACTIVE_LINK" 2>/dev/null || true)
    while IFS= read -r name; do
    if [ "$SERVERS_ROOT/$name" = "$active" ]; then
        echo "* $name"
    else
        echo "  $name"
    fi
    done < <(list_names)
}

cmd_select() {
    need_root
    local name="${1:-}" was_active=false
    if [ -z "$name" ]; then
    [ -t 0 ] || die "no server given and not on a terminal"
    name=$(list_names | fzf --prompt="Select a server: " --height=40% --reverse) || exit 1
    fi
    valid_name "$name" || die "invalid server name: $name"
    [ -d "$SERVERS_ROOT/$name" ] || die "no such server: $name"
    [ -x "$SERVERS_ROOT/$name/run.sh" ] || die "$name has no executable run.sh"
    if [ -e "$ACTIVE_LINK" ] && [ ! -L "$ACTIVE_LINK" ]; then
    die "$ACTIVE_LINK exists and is not a symlink"
    fi

    if systemctl is-active --quiet "$SERVICE"; then
    was_active=true
    systemctl stop "$SERVICE"
    fi
    ln -sfn "$SERVERS_ROOT/$name" "$ACTIVE_LINK"
    chown -h "$MC_USER:$MC_GROUP" "$ACTIVE_LINK"
    if [ "$was_active" = true ]; then
    systemctl start "$SERVICE"
    fi
    echo "active server: $name"
}

cmd_create() {
    need_root
    local name="${1:-}" java="${2:-}" dir
    if [ -z "$name" ] || [ -z "$java" ]; then
    die "usage: mc-select create <server> <8|17|25>"
    fi
    valid_name "$name" || die "invalid server name: $name"
    case "$java" in
    8|17|25) ;;
    *) die "unsupported java version: $java" ;;
    esac
    dir="$SERVERS_ROOT/$name"
    [ ! -e "$dir" ] || die "already exists: $dir"

    install -d -m 0750 -o "$MC_USER" -g "$MC_GROUP" "$dir"

    cat > "$dir/eula.txt" <<EOF
# https://aka.ms/MinecraftEULA
eula=true
EOF

    cat > "$dir/run.sh" <<EOF
#!/usr/bin/env bash
# Base launcher generated by mc-select: adjust heap and launch line for your loader.
# Forge 1.17+: @user_jvm_args.txt @libraries/net/minecraftforge/forge/<ver>/unix_args.txt nogui
# Fabric:      -jar fabric-server-launch.jar nogui
exec java-version $java \\
    -Xms2G -Xmx4G \\
    -jar server.jar nogui
EOF

    chmod 0755 "$dir/run.sh"
    chown "$MC_USER:$MC_GROUP" "$dir/run.sh" "$dir/eula.txt"
    echo "created $dir (java $java); drop the server files in, then: mc-select select $name"
}

case "${1:-}" in
    list|ls)    cmd_list ;;
    select|sel) shift; cmd_select "$@" ;;
    create|new) shift; cmd_create "$@" ;;
    *)          usage ;;
esac